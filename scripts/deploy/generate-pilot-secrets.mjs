// PROD-03-03 — one-time key and secret generation for the pilot Compose kit.
//
// Runs once, as the pilot kit's `witness-init` tool (no network, only the
// witness's volume mounted), so the witness receipt key is created where only
// the witness reads it:
//
//   docker compose run --rm -T witness-init \
//     --secret FRONTERA_OPERATOR_KEY_ADMIN --secret FRONTERA_OPERATOR_KEY_OBSERVER >> .env
//
// It prints, as .env lines, on stdout only:
//   - a fresh software-custody authority signing key (CORE-02 `software`; the
//     key is held in the Host process — finding AA-001; use an external signer
//     where that matters) and its trusted verification set;
//   - the witness id, a fresh witness credential and the witness's PUBLIC
//     receipt key, which the Host pins (CORE-07);
//   - a fresh 48-byte random value for every `--secret NAME` (operator and
//     administrator credentials the governed-action file names).
//
// It never prints the witness private key, writes nothing but the witness key
// files, and refuses to run twice: a second authority key or witness key would
// silently break trust in everything the first one signed. Provider
// credentials are not generated — they come from the provider.
//
// An operator or administrator added to the governed-action file later gets
// its credential without touching any key:
//
//   docker compose run --rm -T witness-init --secrets-only --secret FRONTERA_OPERATOR_KEY_NEW >> .env
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { closeSync, existsSync, linkSync, openSync, rmSync, writeFileSync } from 'node:fs';
// Generated credentials live in their own namespace, so a name can never be a
// variable that controls the Host, the runtime or Compose itself (PATH,
// NODE_OPTIONS, COMPOSE_PROFILES, FRONTERA_IMAGE, FRONTERA_PUBLISH_PORT, …).
const ENV_NAME = /^FRONTERA_[A-Z0-9_]+$/;
const RESERVED = /^FRONTERA_(REFERENCE_|PROVIDER_|IMAGE$|PUBLISH_|BUILD_)/;

function refuse(message) {
  console.error(`generate-pilot-secrets refused: ${message}`);
  process.exit(1);
}

const args = process.argv.slice(2);
const secretsOnly = args.includes('--secrets-only');
const secretNames = [];
for (let index = 0; index < args.length; index += 1) {
  if (args[index] === '--secrets-only') continue;
  if (args[index] !== '--secret' || args[index + 1] === undefined) refuse('usage: generate-pilot-secrets.mjs [--secrets-only] [--secret NAME]...');
  const name = args[index + 1];
  if (!ENV_NAME.test(name) || RESERVED.test(name)) refuse(`'${name}' is not an allowed credential name: use FRONTERA_<NAME> (uppercase, digits, underscores), not one of the kit's own FRONTERA_IMAGE, FRONTERA_PUBLISH_*, FRONTERA_BUILD_*, FRONTERA_REFERENCE_* variables.`);
  if (secretNames.includes(name)) refuse(`'${name}' is named twice.`);
  secretNames.push(name);
  index += 1;
}

const secret = () => randomBytes(48).toString('base64url');

if (secretsOnly) {
  if (secretNames.length === 0) refuse('--secrets-only needs at least one --secret NAME.');
  // Exit only once stdout has taken every byte (a pipe into `>> .env`).
  const block = `\n# ---- generated by scripts/deploy/generate-pilot-secrets.mjs --secrets-only (${new Date().toISOString()}) ----\n${secretNames.map((name) => `${name}=${secret()}`).join('\n')}\n# ---- end generated ----\n`;
  await new Promise((resolveWrite) => process.stdout.write(block, (error) => (error ? refuse('the generated secrets could not be written out; run it again.') : resolveWrite())));
  process.exit(0);
}

const keyFile = process.env.FRONTERA_REFERENCE_WITNESS_KEY_FILE;
if (keyFile === undefined || keyFile.length === 0) refuse('FRONTERA_REFERENCE_WITNESS_KEY_FILE is not set; run this as the witness-init tool.');
// One initialization at a time: two concurrent runs would print two different
// key sets, and only one can be persisted. Taken before anything is checked,
// generated or printed; released however this process exits.
const lock = `${keyFile}.init.lock`;
try {
  closeSync(openSync(lock, 'wx', 0o600));
} catch {
  refuse(`another initialization holds ${lock.split('/').pop()} in the witness volume. If none is running, a previous one was killed: delete that file and run again.`);
}
process.on('exit', () => rmSync(lock, { force: true }));
if (existsSync(keyFile)) {
  refuse('this deployment is already initialized (the witness receipt key exists). Generating new authority or witness keys would break trust in every artifact the current ones signed.');
}

// The witness receipt key is generated here, in memory, and persisted only
// after the whole block below has been written out (see the end): an
// interrupted run, or a failed `>> .env`, leaves nothing behind and can simply
// be run again. Same files, formats and modes as the witness's own
// loadOrCreateReferenceWitnessKey.
const witnessKeys = generateKeyPairSync('ed25519');
const witness = {
  privateKeyPem: witnessKeys.privateKey.export({ type: 'pkcs8', format: 'pem' }).toString(),
  publicKeyPem: witnessKeys.publicKey.export({ type: 'spki', format: 'pem' }).toString(),
};

const stamp = new Date().toISOString().slice(0, 10).replaceAll('-', '');
const suffix = randomBytes(4).toString('hex');
const signingKeyId = `frontera-authority-${stamp}-${suffix}`;
const { privateKey, publicKey } = generateKeyPairSync('ed25519');
const privatePem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString();
const publicPem = publicKey.export({ type: 'spki', format: 'pem' }).toString();

/** A PEM as one double-quoted .env value: Compose turns `\n` back into newlines. */
const pemValue = (pem) => `"${pem.trim().split('\n').join('\\n')}\\n"`;

const lines = [
  '',
  `# ---- generated by scripts/deploy/generate-pilot-secrets.mjs (${new Date().toISOString()}) ----`,
  '# Secret. Never commit, never back up with the data volumes, never paste into a ticket.',
  `AOC_ENTERPRISE_AUTHORITY_SIGNING_KEY_ID=${signingKeyId}`,
  `AOC_ENTERPRISE_AUTHORITY_SIGNING_KEY_PEM=${pemValue(privatePem)}`,
  `AOC_ENTERPRISE_AUTHORITY_VERIFICATION_KEYS='${JSON.stringify([{ keyId: signingKeyId, algorithm: 'ed25519-v1', publicKeyPem: publicPem }])}'`,
  `AOC_ENTERPRISE_AUTHORITY_FRESHNESS_WITNESS_ID=frontera-witness-${suffix}`,
  `AOC_ENTERPRISE_AUTHORITY_FRESHNESS_TOKEN=${secret()}`,
  `AOC_ENTERPRISE_AUTHORITY_FRESHNESS_WITNESS_PUBLIC_KEY=${pemValue(witness.publicKeyPem)}`,
  ...secretNames.map((name) => `${name}=${secret()}`),
  '# ---- end generated ----',
];
process.stdout.write(`${lines.join('\n')}\n`, (error) => {
  // Only once stdout has accepted every byte is the deployment initialized.
  if (error) refuse('the generated block could not be written out; nothing was persisted, run it again.');
  // The public half first: the private key file is what marks the deployment
  // initialized, so it is written last, and only a complete pair ever marks it.
  // The private key appears whole or not at all: written to a temporary file,
  // then hard-linked into place (atomic, and never over an existing key).
  const staged = `${keyFile}.tmp-${randomBytes(6).toString('hex')}`;
  try {
    writeFileSync(`${keyFile}.pub`, witness.publicKeyPem, { mode: 0o644, flag: 'w' });
    writeFileSync(staged, witness.privateKeyPem, { mode: 0o600, flag: 'wx' });
    linkSync(staged, keyFile);
  } catch {
    refuse('the witness receipt key could not be stored; discard the block just printed and run it again.');
  } finally {
    rmSync(staged, { force: true });
  }
});
