// PROD-03-03 — one-time key and secret generation for the pilot Compose kit.
//
// Runs once, inside the bundled reference witness's container, so the witness
// receipt key is created where only the witness reads it (its own volume):
//
//   docker compose run --rm -T authority-witness node scripts/deploy/generate-pilot-secrets.mjs \
//     --secret FRONTERA_OPERATOR_KEY_ADMIN --secret FRONTERA_OPERATOR_KEY_OBSERVER >> .env
//
// It prints, as .env lines, on stdout only:
//   - a fresh software-custody authority signing key (CORE-02 `software`; the
//     key is held in the Host process — finding AA-001; use an external signer
//     where that matters) and its trusted verification set;
//   - the witness id, a fresh witness credential and the witness's PUBLIC
//     receipt key, which the Host pins (CORE-07);
//   - a fresh 48-byte random value for every `--secret NAME` (operator and
//     administrator credentials the governed-action file names).
//
// It never prints the witness private key, writes nothing but the witness key
// files, and refuses to run twice: a second authority key or witness key would
// silently break trust in everything the first one signed. Provider
// credentials are not generated — they come from the provider.
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const ENV_NAME = /^[A-Z_][A-Z0-9_]*$/;
const RESERVED = /^AOC_ENTERPRISE_|^FRONTERA_REFERENCE_/;

function refuse(message) {
  console.error(`generate-pilot-secrets refused: ${message}`);
  process.exit(1);
}

const args = process.argv.slice(2);
const secretNames = [];
for (let index = 0; index < args.length; index += 1) {
  if (args[index] !== '--secret' || args[index + 1] === undefined) refuse('usage: generate-pilot-secrets.mjs [--secret NAME]...');
  const name = args[index + 1];
  if (!ENV_NAME.test(name) || RESERVED.test(name)) refuse(`'${name}' is not an allowed variable name (uppercase, digits, underscores; not AOC_ENTERPRISE_* or FRONTERA_REFERENCE_*).`);
  if (secretNames.includes(name)) refuse(`'${name}' is named twice.`);
  secretNames.push(name);
  index += 1;
}

const keyFile = process.env.FRONTERA_REFERENCE_WITNESS_KEY_FILE;
if (keyFile === undefined || keyFile.length === 0) refuse('FRONTERA_REFERENCE_WITNESS_KEY_FILE is not set; run this in the authority-witness service.');
if (existsSync(keyFile)) {
  refuse('this deployment is already initialized (the witness receipt key exists). Generating new authority or witness keys would break trust in every artifact the current ones signed.');
}

const { loadOrCreateReferenceWitnessKey } = await import(resolve(root, 'dist/src/enterprise/authority-state-freshness/reference/reference-witness-service.js'));
const witness = loadOrCreateReferenceWitnessKey(keyFile);

const stamp = new Date().toISOString().slice(0, 10).replaceAll('-', '');
const suffix = randomBytes(4).toString('hex');
const signingKeyId = `frontera-authority-${stamp}-${suffix}`;
const { privateKey, publicKey } = generateKeyPairSync('ed25519');
const privatePem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString();
const publicPem = publicKey.export({ type: 'spki', format: 'pem' }).toString();
const secret = () => randomBytes(48).toString('base64url');

/** A PEM as one double-quoted .env value: Compose turns `\n` back into newlines. */
const pemValue = (pem) => `"${pem.trim().split('\n').join('\\n')}\\n"`;

const lines = [
  '',
  `# ---- generated by scripts/deploy/generate-pilot-secrets.mjs (${new Date().toISOString()}) ----`,
  '# Secret. Never commit, never back up with the data volumes, never paste into a ticket.',
  `AOC_ENTERPRISE_AUTHORITY_SIGNING_KEY_ID=${signingKeyId}`,
  `AOC_ENTERPRISE_AUTHORITY_SIGNING_KEY_PEM=${pemValue(privatePem)}`,
  `AOC_ENTERPRISE_AUTHORITY_VERIFICATION_KEYS='${JSON.stringify([{ keyId: signingKeyId, algorithm: 'ed25519-v1', publicKeyPem: publicPem }])}'`,
  `AOC_ENTERPRISE_AUTHORITY_FRESHNESS_WITNESS_ID=frontera-witness-${suffix}`,
  `AOC_ENTERPRISE_AUTHORITY_FRESHNESS_TOKEN=${secret()}`,
  `AOC_ENTERPRISE_AUTHORITY_FRESHNESS_WITNESS_PUBLIC_KEY=${pemValue(witness.publicKeyPem)}`,
  ...secretNames.map((name) => `${name}=${secret()}`),
  '# ---- end generated ----',
];
process.stdout.write(`${lines.join('\n')}\n`);
