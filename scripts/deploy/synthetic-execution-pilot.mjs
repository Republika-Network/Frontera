#!/usr/bin/env node
// AUTH-04D2S — the synthetic Authority pilot's verified synthetic execution:
// one-time initialization and configuration rendering. Run as the Compose
// tools in deploy/authority-pilot/compose.executor.yaml, never by hand on the
// Host process, and never with network access:
//
//   executor-init   synthetic-executor-init (the executor's own volume only):
//                   the executor's receipt key, its G-02A consumption ledger,
//                   its receipt ledger and its output directory. Prints the
//                   receipt PUBLIC key (and writes it to --public-key-out, the
//                   one file it writes outside its volume) and a fresh executor client credential
//                   (FRONTERA_SYNTHETIC_EXECUTOR_TOKEN) — the one secret the
//                   Host's adapter and the executor share. Refuses a second run.
//   host-init       execution-init (the Host's state volume only): the G-02B
//                   issuance ledger and the G-02C1D receipt evidence store.
//                   Prints the execution verifier's read-only auditor
//                   credential (AUTH-04D2V). Refuses a second run.
//   render          synthetic-execution-render (the kit read-only and one
//                   output directory holding the executor's PUBLIC key; never
//                   the executor's volume):
//                   the Host's governed-action file (the pilot policy plus
//                   deploy/authority-pilot/synthetic-execution.additions.json)
//                   and the executor's closed configuration, pinned to the
//                   Host's PUBLIC authority keys and the executor's PUBLIC
//                   receipt key. Writes public configuration only; refuses to
//                   overwrite.
//
// Synthetic only. The executor performs one local synthetic record write per
// verified, single-use, request-bound capability (G-02C1B); it has no
// downstream, no credential to anything, and no route to anything else. The
// .invalid failure route of the pilot policy is left exactly as it is.
//
// Run after `npm run build` (inside the pilot image, dist/ is present).

import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const dist = (path) => join(ROOT, 'dist/src/enterprise', path);

function refuse(message) {
  process.stderr.write(`synthetic-execution-pilot: ${message}\n`);
  process.exit(1);
}

function required(name) {
  const value = process.env[name];
  if (value === undefined || value.trim().length === 0) refuse(`${name} is required.`);
  return value.trim();
}

const PLACEHOLDER = /<[^>]*>/;

/** The executor's state, under its own volume (mounted at /var/lib/frontera in the executor's containers only). */
function executorPaths(additions) {
  const executor = additions.executor;
  return {
    state: join(executor.syntheticExecution.outputDirectory, '..'),
    ledger: executor.syntheticExecution.consumptionLedgerPath,
    output: executor.syntheticExecution.outputDirectory,
    key: executor.executorReceipts.privateKeyFile,
    receipts: executor.executorReceipts.receiptLedgerPath,
  };
}

function readAdditions(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

async function executorInit(additionsPath, publicKeyOut) {
  const additions = readAdditions(additionsPath);
  const paths = executorPaths(additions);
  if (existsSync(paths.key)) refuse('this executor is already initialized (its receipt key exists). A new receipt key would silently change what the Host pins.');
  for (const directory of [paths.state, join(paths.key, '..'), join(paths.ledger, '..'), join(paths.receipts, '..'), paths.output]) mkdirSync(directory, { recursive: true, mode: 0o700 });
  const { openExecutionCapabilityConsumptionLedger } = await import(dist('execution-capability/reference/consumption-ledger.js'));
  const { openExecutorReceiptLedger } = await import(dist('reference-executor/receipt-ledger.js'));
  const { audience, executorId } = additions.executor;
  (await openExecutionCapabilityConsumptionLedger(paths.ledger, { audience, clock: () => Date.now(), create: true })).close();
  (await openExecutorReceiptLedger(paths.receipts, { executorId, audience, clock: () => Date.now(), create: true })).close();
  const { privateKey, publicKey } = generateKeyPairSync('ed25519');
  const publicPem = publicKey.export({ type: 'spki', format: 'pem' }).toString();
  // The private key last: an interrupted run leaves no key, and can simply be run again.
  writeFileSync(publicKeyOut, publicPem, { mode: 0o644, flag: 'wx' });
  writeFileSync(paths.key, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600, flag: 'wx' });
  process.stdout.write(
    [
      `# ---- generated by scripts/deploy/synthetic-execution-pilot.mjs executor-init (${new Date().toISOString()}) ----`,
      '# The executor client credential: secret. Into deploy/pilot/.env (the Host adapter and the executor read it); never commit it.',
      `FRONTERA_SYNTHETIC_EXECUTOR_TOKEN=${randomBytes(48).toString('base64url')}`,
      `# The executor receipt PUBLIC key (${additions.executor.executorReceipts.keyId}), also written to ${publicKeyOut} for render.`,
      ...publicPem.trim().split('\n').map((line) => `# ${line}`),
      '# ---- end generated ----',
      '',
    ].join('\n'),
  );
}

async function hostInit(kit) {
  const additions = readAdditions(join(kit, 'synthetic-execution.additions.json'));
  const organizationId = required('AOC_ENTERPRISE_KERNEL_AUTHORITY_ORGANIZATION_ID');
  const trustDomain = JSON.parse(readFileSync(join(kit, 'governed-actions.synthetic-pilot.json'), 'utf8')).trustDomainId;
  const capabilities = additions.executionCapabilities;
  const evidence = capabilities.receiptEvidence.storePath;
  if (existsSync(capabilities.issuanceLedgerPath) || existsSync(evidence)) refuse('the issuance ledger or the evidence store already exists; host-init runs once.');
  const { openExecutionCapabilityIssuanceLedger } = await import(dist('execution-capability-issuance/index.js'));
  const { openExecutionReceiptEvidenceStore } = await import(dist('execution-receipt-evidence/index.js'));
  (await openExecutionCapabilityIssuanceLedger(capabilities.issuanceLedgerPath, { issuer: capabilities.issuer, clock: Date.now, create: true })).close();
  // The evidence store refuses a directory others can write.
  mkdirSync(join(evidence, '..'), { recursive: true, mode: 0o700 });
  (await openExecutionReceiptEvidenceStore(evidence, { issuer: capabilities.issuer, organizationId, trustDomain, clock: Date.now, create: true })).close();
  process.stdout.write(
    [
      `# ---- generated by scripts/deploy/synthetic-execution-pilot.mjs host-init (${new Date().toISOString()}) ----`,
      '# The issuance ledger and the receipt evidence store were created.',
      `# The execution verifier's read-only auditor credential (${additions.auditor.auditorId}): secret. Into deploy/pilot/.env; never commit it.`,
      `${additions.auditor.apiKeyEnv}=${randomBytes(48).toString('base64url')}`,
      '# ---- end generated ----',
      '',
    ].join('\n'),
  );
}

/** The pilot policy plus the synthetic success route, pinned to the executor's PUBLIC receipt key. */
export function renderPolicy(base, additions, { organizationId, executorPublicKeyPem }) {
  const policy = structuredClone(base);
  const template = policy.governance.profiles.find((profile) => profile.approval !== undefined);
  if (template === undefined) throw new Error('the base policy has no approval profile to take owner, provenance and policies from.');
  const add = additions.governance;
  for (const dimension of add.parameterDimensions) if (!policy.governance.parameterDimensions.some((existing) => existing.id === dimension.id)) policy.governance.parameterDimensions.push(dimension);
  policy.governance.actionClasses.push(...add.actionClasses);
  policy.governance.resourceClasses.push(...add.resourceClasses);
  policy.governance.profiles.push(...add.profiles.map((profile) => ({ ...profile, owner: template.owner, provenance: template.provenance, relevantPolicies: template.relevantPolicies })));
  policy.approvalPolicy.rules.push(additions.approvalRule);
  policy.genericHttpAdapters.push(additions.genericHttpAdapter);
  policy.routes.push(additions.route);
  // AUTH-04D2V: the read-only, organization-scoped auditor the execution verifier reads ASSURE-01 traces as (an existing contract).
  policy.auditors = [...(policy.auditors ?? []), additions.auditor];
  const { receiptEvidence, ...capabilities } = additions.executionCapabilities;
  const trusted = receiptEvidence.trustedExecutor;
  policy.executionCapabilities = {
    ...capabilities,
    receiptEvidence: {
      storePath: receiptEvidence.storePath,
      trustedExecutors: [
        {
          executorId: trusted.executorId,
          keys: [{ keyId: trusted.keyId, algorithm: 'ed25519-v1', publicKeyPem: executorPublicKeyPem.trim() }],
          audiences: trusted.audiences,
          organizationIds: [organizationId],
          trustDomains: [policy.trustDomainId],
        },
      ],
    },
  };
  return policy;
}

/** The executor's closed configuration, pinned to the Host's PUBLIC authority keys alone. */
export function renderExecutor(additions, { organizationId, trustDomain, authorityVerificationKeys }) {
  const { issuer, ...executor } = additions.executor;
  return {
    ...executor,
    organizationIds: [organizationId],
    trustDomain,
    trustedIssuers: [{ issuer, keys: authorityVerificationKeys.map(({ keyId, algorithm, publicKeyPem }) => ({ keyId, algorithm, publicKeyPem })) }],
  };
}

function render(kit, out, executorPublicKeyFile) {
  const additions = readAdditions(join(kit, 'synthetic-execution.additions.json'));
  const base = JSON.parse(readFileSync(join(kit, 'governed-actions.synthetic-pilot.json'), 'utf8'));
  const organizationId = required('AOC_ENTERPRISE_KERNEL_AUTHORITY_ORGANIZATION_ID');
  const authorityVerificationKeys = JSON.parse(required('AOC_ENTERPRISE_AUTHORITY_VERIFICATION_KEYS'));
  if (!Array.isArray(authorityVerificationKeys) || authorityVerificationKeys.length === 0) refuse('AOC_ENTERPRISE_AUTHORITY_VERIFICATION_KEYS must list the Host authority PUBLIC keys.');
  if (JSON.stringify(authorityVerificationKeys).includes('PRIVATE KEY')) refuse('AOC_ENTERPRISE_AUTHORITY_VERIFICATION_KEYS holds a private key; only public keys are pinned.');
  const executorPublicKeyPem = readFileSync(executorPublicKeyFile, 'utf8');
  if (!executorPublicKeyPem.includes('BEGIN PUBLIC KEY') || executorPublicKeyPem.includes('PRIVATE')) refuse('the executor receipt key file is not a public key.');
  const policy = renderPolicy(base, additions, { organizationId, executorPublicKeyPem });
  const executor = renderExecutor(additions, { organizationId, trustDomain: base.trustDomainId, authorityVerificationKeys });
  for (const [name, document] of [['governed-actions.json', policy], ['synthetic-executor.json', executor]]) {
    const text = `${JSON.stringify(document, null, 2)}\n`;
    if (PLACEHOLDER.test(text.replace(/-----(BEGIN|END) PUBLIC KEY-----/g, ''))) refuse(`${name} still holds a placeholder.`);
    writeFileSync(join(out, name), text, { mode: 0o644, flag: 'wx' });
  }
  process.stdout.write(`synthetic-execution-pilot: rendered ${join(out, 'governed-actions.json')} and ${join(out, 'synthetic-executor.json')} (public configuration only).\n`);
}

const [command, ...rest] = process.argv.slice(2);
const option = (name, fallback) => {
  const index = rest.indexOf(name);
  if (index === -1) return fallback;
  const value = rest[index + 1];
  if (value === undefined) refuse(`${name} needs a value.`);
  return value;
};
const KIT = option('--kit', join(ROOT, 'deploy/authority-pilot'));

if (import.meta.url === new URL(process.argv[1] ?? '', 'file:').href) {
  try {
    if (command === 'executor-init') {
      const publicKeyOut = option('--public-key-out', undefined);
      if (publicKeyOut === undefined) refuse('executor-init needs --public-key-out <file>.');
      await executorInit(join(KIT, 'synthetic-execution.additions.json'), publicKeyOut);
    }
    else if (command === 'host-init') await hostInit(KIT);
    else if (command === 'render') {
      const out = option('--out', undefined);
      if (out === undefined) refuse('render needs --out <directory>.');
      const publicKey = option('--executor-public-key', undefined);
      if (publicKey === undefined) refuse('render needs --executor-public-key <file>.');
      render(KIT, out, publicKey);
    }
    else refuse('usage: synthetic-execution-pilot.mjs executor-init --public-key-out <file> | host-init | render --out <directory> --executor-public-key <file> [--kit <directory>]');
  } catch (error) {
    refuse(error instanceof Error ? error.message : String(error));
  }
}
