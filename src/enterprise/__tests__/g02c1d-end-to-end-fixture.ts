// ── A byte relay between the Host's transport and the executor ─────────────

export interface Relay {
  /** Where the Host's transport dials. */
  readonly target: { readonly path: string };
  /** Every request's raw bytes, as the Host wrote them. */
  readonly requests: Buffer[];
  close(): Promise<void>;
}

export interface RelayOptions {
  /** Forward the request, then drop the Host's connection when the answer starts: the executor acted, the Host never hears. */
  readonly dropResponse?: boolean;
  /** Wait this long before forwarding. */
  readonly delayMs?: number;
  /** Keep the request and never forward it; the Host's connection is dropped. */
  readonly hold?: boolean;
}

/**
 * A transparent relay on a Unix socket in `dir`, forwarding to the executor's loopback port. Bytes pass unchanged; it only
 * delays, holds or drops. (A Unix socket has no remote address, so the transport's connect-address check is not exercised
 * through it — the address policy is not qualified by these tests in any case.)
 */
export async function startRelay(dir: string, executorPort: number, options: RelayOptions = {}): Promise<Relay> {
  const path = join(dir, `relay-${Math.random().toString(16).slice(2, 10)}.sock`);
  const requests: Buffer[] = [];
  const sockets = new Set<Socket>();
  const server: Server = createNetServer((client) => {
    sockets.add(client);
    let bytes = Buffer.alloc(0);
    let forwarded = false;
    client.on('data', (chunk: Buffer) => {
      bytes = Buffer.concat([bytes, chunk]);
      const end = bytes.indexOf('\r\n\r\n');
      if (end === -1 || forwarded) return;
      const length = /\r\ncontent-length:\s*([0-9]+)/i.exec(bytes.subarray(0, end).toString('latin1'));
      if (bytes.length - (end + 4) < (length === null ? 0 : Number(length[1]))) return;
      forwarded = true;
      requests.push(bytes);
      if (options.hold === true) {
        client.destroy();
        return;
      }
      const forward = (): void => {
        const upstream = connect({ host: '127.0.0.1', port: executorPort });
        sockets.add(upstream);
        upstream.on('error', () => client.destroy());
        upstream.on('data', (answer: Buffer) => {
          if (options.dropResponse === true) {
            client.destroy();
            upstream.destroy();
            return;
          }
          client.write(answer);
        });
        upstream.on('end', () => client.end());
        upstream.write(bytes);
      };
      if (options.delayMs === undefined) forward();
      else setTimeout(forward, options.delayMs);
    });
    client.on('error', () => undefined);
  });
  await new Promise<void>((ready) => server.listen(path, () => ready()));
  return {
    target: { path },
    requests,
    close: () =>
      new Promise<void>((done) => {
        for (const socket of sockets) socket.destroy();
        server.close(() => done());
      }),
  };
}

export interface HostWorldOptions {
  /** The issuance policy's capability lifetime (default 30 s). */
  readonly lifetimeMs?: number;
  /** Where the transport dials (the executor, a forger, or a relay). Ignored with `respond`. */
  readonly target?: { readonly port: number } | { readonly path: string };
  /** In place of the transport: answers the exact request the adapter handed it (an in-process executor or adversary). */
  readonly respond?: (request: GenericHttpWireRequest) => GenericHttpTransportObservation | Promise<GenericHttpTransportObservation>;
  readonly trustedExecutors: readonly TrustedExecutor[];
  /** Rewrites the request after the adapter appended the presentation, before the transport writes it (a man in the middle). */
  readonly tamper?: (request: GenericHttpWireRequest) => GenericHttpWireRequest;
  /** Makes the evidence store unavailable before the recorder runs (a Host crash before persistence). */
  readonly evidenceUnavailable?: boolean;
}

export async function hostWorld(options: HostWorldOptions): Promise<HostWorld> {
  const dir = privateDirectory('frontera-g02c1d-host-');
  const now = (): number => Date.now();
  const issuance = await openExecutionCapabilityIssuanceLedger(join(dir, 'issuance.sqlite'), { issuer: G02B_ISSUER, clock: now, create: true });
  const evidence = await openE2EEvidenceStore(join(dir, 'receipt-evidence.sqlite'));
  const grants: SignedGrant[] = [];
  const revoked: string[] = [];
  const policyInputs = options.lifetimeMs === undefined ? E2E_POLICY_INPUT : { ...E2E_POLICY_INPUT, lifetimeMs: options.lifetimeMs };
  const policy = options.lifetimeMs === undefined ? E2E_POLICY : createExecutionCapabilityIssuancePolicy(policyInputs);
  const issuer = createExecutionCapabilityIssuer({ grants: readerOf(grants, revoked), signer: custodySigner(AUTHORITY_KEY_A, policyInputs, now), verifier: testVerifier([AUTHORITY_KEY_A]), policy, ledger: issuance, now });
  const gate = createExecutionCapabilityGate({ adapterId: E2E_ADAPTER_ID, audience: E2E_AUDIENCE, policy, issuer, clock: now });
  gate.bind({ issuerKey: trustedKeyOf(AUTHORITY_KEY_A), emergencyControl: undefined });
  const recorder = createExecutionReceiptEvidenceRecorder({
    adapterId: E2E_ADAPTER_ID,
    executorId: E2E_EXECUTOR_ID,
    audience: E2E_AUDIENCE,
    issuer: G02B_ISSUER,
    organizationId: G02B_ORGANIZATION,
    trustDomain: G02B_TRUST_DOMAIN,
    verifier: createExecutionReceiptTrust(options.trustedExecutors),
  });
  recorder.bind({ issuance, store: evidence });
  const sent: GenericHttpWireRequest[] = [];
  const exchanges: GenericHttpExchangeEvidence[] = [];
  // The adapter runs its observer detached, after returning; the world's `execute` waits for it so a test reads settled evidence.
  const pending: Promise<void>[] = [];
  const primitive = options.target === undefined ? undefined : loopbackHostPrimitive(options.target);
  const adapter = createGenericHttpExecutionAdapterCore(
    gatedPlan({ adapterId: E2E_ADAPTER_ID, origin: `https://${E2E_HOSTNAME}`, timeoutMs: 5_000 }),
    {
      resolve: async () => ({ kind: 'resolved', answers: [PUBLIC_ANSWER] }),
      send: (request, _address, timeoutMs, providerRefHeader) => {
        sent.push(request);
        const outbound = options.tamper === undefined ? request : options.tamper(request);
        if (options.respond !== undefined) return Promise.resolve(options.respond(outbound));
        assert.ok(primitive !== undefined, 'a host world needs a target or a responder');
        return sendOnce(primitive, outbound, { address: '127.0.0.1', family: 4 }, timeoutMs, providerRefHeader);
      },
    },
    gate.beforeSend,
    (exchange) => {
      const observed = (async () => {
        exchanges.push(exchange);
        if (options.evidenceUnavailable === true) evidence.close();
        await recorder.observe(exchange);
      })();
      pending.push(observed);
      return observed;
    },
  );
  return {
    dir,
    issuance,
    evidence,
    recorder,
    adapter,
    sent,
    exchanges,
    grant: async () => {
      const signed = await signedGrant({ action: SYNTHETIC_ACTION, issuedAt: Date.now() - 60_000, expiresAt: Date.now() + 3_600_000 });
      grants.push(signed);
      return signed;
    },
    actionFor: (signed) => actionFor(signed, { organization: G02B_ORGANIZATION }),
    revoke: (signed) => {
      revoked.push(signed.grant.id);
    },
    execute: async (action) => {
      const result = await adapter.execute(action);
      await afterObservers();
      await Promise.all(pending.splice(0));
      return result;
    },
    close: () => {
      issuance.close();
      evidence.close();
      rmSync(dir, { recursive: true, force: true });
    },
  };
}

export const executionIdOf = (signed: SignedGrant): string => executionIdForGrant(signed.grant);

// ── Attack helpers (test-only): what an adversary with a key could send ────

/** A CORE-02 envelope over the receipt domain and `text`, under the key in `keyFile` and the key id `keyId`. */
export function signReceiptText(keyFile: string, text: string, keyId: string = E2E_RECEIPT_KEY_ID): Readonly<Record<string, string>> {
  const signature = sign(null, Buffer.from(`${EXECUTOR_RECEIPT_SIGNING_DOMAIN}${text}`, 'utf8'), createPrivateKey(readFileSync(keyFile, 'utf8'))).toString('base64url');
  return Object.freeze({ algorithm: 'ed25519-v1', artifactVersion: AUTHORITY_ARTIFACT_VERSION, keyId, signature });
}

/** The transport encoding of `text` signed under `keyFile`. */
export function deliverable(keyFile: string, text: string, keyId: string = E2E_RECEIPT_KEY_ID): string {
  return encodeExecutorReceiptTransport({ receipt: text, signature: signReceiptText(keyFile, text, keyId) });
}

/** The capability a request presents (the adapter's one header), decoded and parsed — never verified here. */
export function presentedCapability(request: GenericHttpWireRequest): ExecutionCapability {
  const values = request.headers.filter(([name]) => name === EXECUTION_CAPABILITY_PRESENTATION_HEADER).map(([, value]) => value);
  assert.equal(values.length, 1, 'exactly one presentation header');
  const decoded = decodeExecutionCapabilityPresentation(values[0]);
  assert.ok(decoded.ok);
  const parsed = parseExecutionCapability(decoded.presentation.capability);
  assert.ok(parsed.ok);
  return parsed.capability;
}

/** A well-formed receipt about `capability`, as the executor would state a completed synthetic effect, with `overrides` applied. */
export function receiptAbout(capability: ExecutionCapability, overrides: Partial<Record<keyof ExecutorReceiptDraft, unknown>> = {}, position: { readonly sequence?: number; readonly supersedes?: string | null } = {}): ExecutorReceipt {
  // Deterministic, so two receipts about one capability share their subject: the claim at the moment of issuance.
  const claimedAt = capability.issuedAt;
  const { consumption, ...rest } = overrides as { readonly consumption?: Record<string, unknown> } & Record<string, unknown>;
  const draft = {
    format: EXECUTOR_RECEIPT_FORMAT,
    executorId: E2E_EXECUTOR_ID,
    executorKeyId: E2E_RECEIPT_KEY_ID,
    issuer: capability.issuer,
    capabilityId: capability.capabilityId,
    executionId: capability.executionId,
    audience: capability.audience,
    organizationId: capability.organizationId,
    trustDomain: capability.trustDomain,
    actionBinding: { format: capability.actionBinding.format, digest: capability.actionBinding.digest },
    outcome: 'completed-observed',
    basis: 'execution-path',
    observedAt: claimedAt,
    observation: { kind: EXECUTOR_RECEIPT_OBSERVATION_KIND, reference: `${capability.capabilityId}.json`, digest: `sha256:${'a'.repeat(64)}` },
    ...rest,
    consumption: { claimedAt, ledgerState: 'completed', ...consumption },
  } as unknown as ExecutorReceiptDraft;
  return positionExecutorReceipt(draft, position.sequence ?? 1, position.supersedes ?? null);
}

/** `receipt`, serialized and signed under `keyFile`, as one receipt header value. */
export function deliverableReceipt(keyFile: string, receipt: ExecutorReceipt, keyId: string = E2E_RECEIPT_KEY_ID): string {
  return deliverable(keyFile, serializeExecutorReceipt(receipt), keyId);
}

/** One turn of the event loop: long enough for the adapter's detached observer (scheduled with `setImmediate`) to start. */
export const afterObservers = (): Promise<void> => new Promise((done) => setImmediate(done));

/** Resolves once `predicate` holds, polling briefly; fails after `timeoutMs`. */
export async function eventually(predicate: () => boolean | Promise<boolean>, timeoutMs = 5_000): Promise<void> {
  const limit = Date.now() + timeoutMs;
  while (!(await predicate())) {
    assert.ok(Date.now() < limit, 'condition not reached in time');
    await new Promise((wake) => setTimeout(wake, 25));
  }
}

