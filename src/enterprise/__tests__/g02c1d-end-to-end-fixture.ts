export interface ExecutorDomain extends SyntheticDomain {
  readonly keyFile: string;
  readonly publicKeyPem: string;
  readonly receiptLedgerPath: string;
  /** The executor's issued receipts for a capability, read through its receipt ledger in this process. */
  receipts(capabilityId: string): Promise<readonly IssuedExecutorReceipt[]>;
}

export async function executorDomain(audience: string = E2E_AUDIENCE): Promise<ExecutorDomain> {
  const domain = await syntheticDomain(audience);
  const keyDirectory = join(domain.root, 'keys');
  const receiptDirectory = join(domain.root, 'receipts');
  mkdirSync(keyDirectory, { mode: 0o700 });
  mkdirSync(receiptDirectory, { mode: 0o700 });
  const { keyFile, publicKeyPem } = generateReceiptKey(keyDirectory);
  const receiptLedgerPath = join(receiptDirectory, 'receipts.sqlite');
  (await openExecutorReceiptLedger(receiptLedgerPath, { executorId: E2E_EXECUTOR_ID, audience, clock: () => Date.now(), create: true })).close();
  return {
    ...domain,
    keyFile,
    publicKeyPem,
    receiptLedgerPath,
    receipts: async (capabilityId) => {
      const ledger = await openExecutorReceiptLedger(receiptLedgerPath, { executorId: E2E_EXECUTOR_ID, audience, clock: () => Date.now() });
      try {
        return ledger.history(capabilityId);
      } finally {
        ledger.close();
      }
    },
  };
}

export interface ExecutorOptions {
  /** `false`: synthetic execution without receipts — the executor answers, and delivers no receipt. */
  readonly receipts?: boolean;
  readonly audience?: string;
  readonly crashAt?: string;
  readonly overrides?: Record<string, unknown>;
}

/** The executor's configuration: pinned to this Host's issuer and active authority key alone. */
export function e2eExecutorConfiguration(domain: ExecutorDomain, options: ExecutorOptions = {}): Record<string, unknown> {
  return executorConfiguration({
    executorId: E2E_EXECUTOR_ID,
    audience: options.audience ?? E2E_AUDIENCE,
    organizationIds: [G02B_ORGANIZATION],
    trustDomain: G02B_TRUST_DOMAIN,
    trustedIssuers: [{ issuer: G02B_ISSUER, keys: [{ ...trustedKeyOf(AUTHORITY_KEY_A) }] }],
    permittedActions: [SYNTHETIC_ACTION],
    permittedResources: [G02B_RESOURCE],
    expectedOrigin: `https://${E2E_HOSTNAME}`,
    methods: ['POST'],
    mode: 'synthetic-execution',
    syntheticExecution: { effect: SYNTHETIC_EFFECT, consumptionLedgerPath: domain.ledgerPath, outputDirectory: domain.outputDirectory, syntheticActions: [SYNTHETIC_ACTION] },
    ...(options.receipts === false ? {} : { executorReceipts: { keyId: E2E_RECEIPT_KEY_ID, privateKeyFile: domain.keyFile, receiptLedgerPath: domain.receiptLedgerPath } }),
    ...(options.crashAt !== undefined ? { faultInjection: { crashAt: options.crashAt } } : {}),
    ...options.overrides,
  });
}

export function spawnE2EExecutor(domain: ExecutorDomain, options: ExecutorOptions = {}): Promise<SpawnedExecutor> {
  return spawnExecutor(e2eExecutorConfiguration(domain, options), { [BEARER_ENV]: CREDENTIAL_TOKEN, ...(options.crashAt !== undefined ? { [FAULT_VARIABLE]: 'enabled' } : {}) });
}

// ── The Host's side ─────────────────────────────────────────────────────────

/** An agent that dials one loopback target whatever the request names; no keep-alive, like the transport's `agent: false`. */
class LoopbackAgent extends Agent {
  constructor(private readonly target: { readonly port: number } | { readonly path: string }) {
    super({ keepAlive: false });
  }

  override createConnection(): Socket {
    const socket = 'path' in this.target ? connect({ path: this.target.path }) : connect({ host: '127.0.0.1', port: this.target.port });
    // No TLS on loopback: the phase after which a loss is "unconfirmed" is reached when TCP connects.
    socket.once('connect', () => socket.emit('secureConnect'));
    return socket;
  }
}

/** The request primitive `sendOnce` calls: the exact options the transport built, over `http:` to loopback, writing `Host` as HTTPS would. */
export function loopbackHostPrimitive(target: { readonly port: number } | { readonly path: string }): GenericHttpRequestPrimitive {
  return (options, onResponse) => httpRequest({ ...options, protocol: 'http:', agent: new LoopbackAgent(target), defaultPort: 443 }, onResponse);
}

/** The pinned executor registry this Host trusts: one executor, its one receipt key, its scope. */
export function e2eTrustedExecutor(publicKeyPem: string, overrides: Partial<TrustedExecutor> = {}): TrustedExecutor {
  return {
    executorId: E2E_EXECUTOR_ID,
    keys: [{ keyId: E2E_RECEIPT_KEY_ID, algorithm: 'ed25519-v1', publicKeyPem }],
    audiences: [E2E_AUDIENCE],
    organizationIds: [G02B_ORGANIZATION],
    trustDomains: [G02B_TRUST_DOMAIN],
    ...overrides,
  };
}

/** A private directory for Host-side files: the evidence store refuses a directory others can write. */
export function privateDirectory(prefix: string): string {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), prefix)));
  return dir;
}

/** The operator's one initialization of the evidence store, then the Host's own open of it. */
export async function openE2EEvidenceStore(path: string): Promise<ExecutionReceiptEvidenceStore> {
  const options = { issuer: G02B_ISSUER, organizationId: G02B_ORGANIZATION, trustDomain: G02B_TRUST_DOMAIN, clock: () => Date.now() };
  (await openExecutionReceiptEvidenceStore(path, { ...options, create: true })).close();
  return openExecutionReceiptEvidenceStore(path, options);
}

export interface HostWorld {
  readonly dir: string;
  readonly issuance: ExecutionCapabilityIssuanceLedger;
  readonly evidence: ExecutionReceiptEvidenceStore;
  readonly recorder: ExecutionReceiptEvidenceRecorder;
  readonly adapter: ExecutionAdapter;
  /** Every request the adapter handed the transport, exactly as handed. */
  readonly sent: GenericHttpWireRequest[];
  /** Every exchange the adapter showed the recorder. */
  readonly exchanges: GenericHttpExchangeEvidence[];
  /** A fresh, Ed25519-signed grant for the synthetic action, valid now. */
  grant(): Promise<SignedGrant>;
  /** The validated action the exercise gate would hand down for `signed`. */
  actionFor(signed: SignedGrant): ValidatedExecutionAction;
  execute(action: ValidatedExecutionAction): Promise<ExecutionAdapterResult>;
  close(): void;
}

export interface HostWorldOptions {
  /** Where the transport dials (the executor, a forger, or a relay). */
  readonly target: { readonly port: number } | { readonly path: string };
  readonly trustedExecutors: readonly TrustedExecutor[];
  /** Rewrites the request after the adapter appended the presentation, before the transport writes it (a man in the middle). */
  readonly tamper?: (request: GenericHttpWireRequest) => GenericHttpWireRequest;
  /** Makes the evidence store unavailable before the recorder runs (a Host crash before persistence). */
  readonly evidenceUnavailable?: boolean;
}

export async function hostWorld(options: HostWorldOptions): Promise<HostWorld> {
  const dir = privateDirectory('frontera-g02c1d-host-');
  const now = (): number => Date.now();
  const issuance = await openExecutionCapabilityIssuanceLedger(join(dir, 'issuance.sqlite'), { issuer: G02B_ISSUER, clock: now, create: true });
  const evidence = await openE2EEvidenceStore(join(dir, 'receipt-evidence.sqlite'));
  const grants: SignedGrant[] = [];
  const issuer = createExecutionCapabilityIssuer({ grants: readerOf(grants), signer: custodySigner(AUTHORITY_KEY_A, E2E_POLICY_INPUT, now), verifier: testVerifier([AUTHORITY_KEY_A]), policy: E2E_POLICY, ledger: issuance, now });
  const gate = createExecutionCapabilityGate({ adapterId: E2E_ADAPTER_ID, audience: E2E_AUDIENCE, policy: E2E_POLICY, issuer, clock: now });
  gate.bind({ issuerKey: trustedKeyOf(AUTHORITY_KEY_A), emergencyControl: undefined });
  const recorder = createExecutionReceiptEvidenceRecorder({
    adapterId: E2E_ADAPTER_ID,
    audience: E2E_AUDIENCE,
    issuer: G02B_ISSUER,
    organizationId: G02B_ORGANIZATION,
    trustDomain: G02B_TRUST_DOMAIN,
    verifier: createExecutionReceiptTrust(options.trustedExecutors),
  });
  recorder.bind({ issuance, store: evidence });
  const sent: GenericHttpWireRequest[] = [];
  const exchanges: GenericHttpExchangeEvidence[] = [];
  const primitive = loopbackHostPrimitive(options.target);
  const adapter = createGenericHttpExecutionAdapterCore(
    gatedPlan({ adapterId: E2E_ADAPTER_ID, origin: `https://${E2E_HOSTNAME}`, timeoutMs: 5_000 }),
    {
      resolve: async () => ({ kind: 'resolved', answers: [PUBLIC_ANSWER] }),
      send: (request, _address, timeoutMs, providerRefHeader) => {
        sent.push(request);
        const outbound = options.tamper === undefined ? request : options.tamper(request);
        return sendOnce(primitive, outbound, { address: '127.0.0.1', family: 4 }, timeoutMs, providerRefHeader);
      },
    },
    gate.beforeSend,
    async (exchange) => {
      exchanges.push(exchange);
      if (options.evidenceUnavailable === true) evidence.close();
      await recorder.observe(exchange);
    },
  );
  return {
    dir,
    issuance,
    evidence,
    recorder,
    adapter,
    sent,
    exchanges,
    grant: async () => {
      const signed = await signedGrant({ action: SYNTHETIC_ACTION, issuedAt: Date.now() - 60_000, expiresAt: Date.now() + 3_600_000 });
      grants.push(signed);
      return signed;
    },
    actionFor: (signed) => actionFor(signed, { organization: G02B_ORGANIZATION }),
    execute: (action) => adapter.execute(action),
    close: () => {
      issuance.close();
      evidence.close();
      rmSync(dir, { recursive: true, force: true });
    },
  };
}

export const executionIdOf = (signed: SignedGrant): string => executionIdForGrant(signed.grant);

// ── Attack helpers (test-only): what an adversary with a key could send ────

/** A CORE-02 envelope over the receipt domain and `text`, under the key in `keyFile` and the key id `keyId`. */
export function signReceiptText(keyFile: string, text: string, keyId: string = E2E_RECEIPT_KEY_ID): Readonly<Record<string, string>> {
  const signature = sign(null, Buffer.from(`${EXECUTOR_RECEIPT_SIGNING_DOMAIN}${text}`, 'utf8'), createPrivateKey(readFileSync(keyFile, 'utf8'))).toString('base64url');
  return Object.freeze({ algorithm: 'ed25519-v1', artifactVersion: AUTHORITY_ARTIFACT_VERSION, keyId, signature });
}

/** The transport encoding of `text` signed under `keyFile`. */
export function deliverable(keyFile: string, text: string, keyId: string = E2E_RECEIPT_KEY_ID): string {
  return encodeExecutorReceiptTransport({ receipt: text, signature: signReceiptText(keyFile, text, keyId) });
}

/** Resolves once `predicate` holds, polling briefly; fails after `timeoutMs`. */
export async function eventually(predicate: () => boolean | Promise<boolean>, timeoutMs = 5_000): Promise<void> {
  const limit = Date.now() + timeoutMs;
  while (!(await predicate())) {
    assert.ok(Date.now() < limit, 'condition not reached in time');
    await new Promise((wake) => setTimeout(wake, 25));
  }
}
