export const E2E_EXECUTOR_ID = 'reference-executor-g02c1d';
export const E2E_RECEIPT_KEY_ID = 'g02c1d-executor-receipt-key-1';
export const E2E_HOSTNAME = 'api.devops.example';
export const E2E_ADAPTER_ID = 'devops.deployment-gateway';
export const FAULT_VARIABLE = 'FRONTERA_REFERENCE_EXECUTOR_FAULT_INJECTION';
/** A public documentation answer for the adapter's resolution; nothing ever dials it. */
