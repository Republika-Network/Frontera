/**
 * G-02C1D end-to-end fixtures — test-only, synthetic, local.
 *
 * **Two processes, one boundary.** The Host side runs in this test process:
 * the real G-02B issuer (software custody, the real issuance ledger), the
 * real G-02C0 gate, the real Generic HTTP adapter core, the real transport
 * (`sendOnce`, the exact request options and bytes), the real receipt
 * evidence recorder and the real evidence store. The executor runs in its own
 * process (`scripts/run-reference-executor.mjs`), in synthetic-execution mode
 * with receipts, pinned to this Host's issuer key alone; its receipt key is
 * generated by a third, separate process, and this process reads only its
 * public half — except the forging helpers below, which exist to attack.
 *
 * **What the loopback cannot qualify.** The request leaves through
 * `node:http` to 127.0.0.1 instead of `node:https` to a public address: there
 * is no TLS, no certificate check, no public DNS, no address-policy decision
 * over a real answer and no proxy. The adapter's resolution answers one
 * public documentation address; the primitive below dials loopback whatever
 * it names, and marks the TLS phase as reached when TCP connects, so a loss
 * after that is "unconfirmed" exactly as it would be after `secureConnect`.
 */

