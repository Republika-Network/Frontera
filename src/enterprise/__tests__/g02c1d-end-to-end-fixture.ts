export interface ExecutorDomain extends SyntheticDomain {
  readonly keyFile: string;
  readonly publicKeyPem: string;
  readonly receiptLedgerPath: string;
  /** The executor's issued receipts for a capability, read through its receipt ledger in this process. */
  receipts(capabilityId: string): Promise<readonly IssuedExecutorReceipt[]>;
}

export async function executorDomain(audience: string = E2E_AUDIENCE): Promise<ExecutorDomain> {
  const domain = await syntheticDomain(audience);
  const keyDirectory = join(domain.root, 'keys');
  const receiptDirectory = join(domain.root, 'receipts');
  mkdirSync(keyDirectory, { mode: 0o700 });
  mkdirSync(receiptDirectory, { mode: 0o700 });
  const { keyFile, publicKeyPem } = generateReceiptKey(keyDirectory);
  const receiptLedgerPath = join(receiptDirectory, 'receipts.sqlite');
  (await openExecutorReceiptLedger(receiptLedgerPath, { executorId: E2E_EXECUTOR_ID, audience, clock: () => Date.now(), create: true })).close();
  return {
    ...domain,
    keyFile,
    publicKeyPem,
    receiptLedgerPath,
    receipts: async (capabilityId) => {
      const ledger = await openExecutorReceiptLedger(receiptLedgerPath, { executorId: E2E_EXECUTOR_ID, audience, clock: () => Date.now() });
      try {
        return ledger.history(capabilityId);
      } finally {
        ledger.close();
      }
    },
  };
}

