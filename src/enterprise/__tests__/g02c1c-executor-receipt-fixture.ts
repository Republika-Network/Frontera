import { inProcessFlow, syntheticConfiguration, syntheticDomain, type InProcessFlow, type SyntheticDomain } from './g02c1b-synthetic-execution-fixture.js';

/**
 * G-02C1C fixtures — test-only, synthetic, local.
 *
 * The executor's receipt key is generated by a **separate key-generation
 * process**, as an operator would: it writes the private key (0600) and its
 * public half beside it. Verifiers in this process are built from the public
 * half only. The in-process unit suites additionally load the signer in this
 * process to exercise it directly; the separate-process suite never does.
 */

export const RECEIPT_KEY_ID = 'g02c1c-executor-receipt-key-1';
export const BINDING_FORMAT = 'frontera.http-request-binding.v1';

export interface GeneratedKey {
  readonly keyFile: string;
  readonly publicKeyPem: string;
}

/** A fresh Ed25519 receipt key, made by another process. This process reads only the `.pub` file. */
export function generateReceiptKey(directory: string, name = 'receipt-key.pem'): GeneratedKey {
  const keyFile = join(directory, name);
  const script = [
    "const crypto = require('node:crypto');",
    "const fs = require('node:fs');",
    "const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');",
    "fs.writeFileSync(process.env.KEY_FILE, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });",
    "fs.writeFileSync(process.env.KEY_FILE + '.pub', publicKey.export({ type: 'spki', format: 'pem' }));",
  ].join('\n');
  const generated = spawnSync(process.execPath, ['-e', script], { env: { PATH: process.env.PATH ?? '', KEY_FILE: keyFile }, encoding: 'utf8' });
  assert.equal(generated.status, 0, generated.stderr);
  return { keyFile, publicKeyPem: readFileSync(`${keyFile}.pub`, 'utf8') };
}

export interface ReceiptDomain extends SyntheticDomain {
  readonly keyDirectory: string;
  readonly keyFile: string;
  readonly publicKeyPem: string;
  readonly receiptLedgerPath: string;
  /** Issued receipts for a capability, read back through the receipt ledger API in this process. */
  history(capabilityId: string): Promise<readonly IssuedExecutorReceipt[]>;
  /** A verifier pinned to this executor's public receipt key only. */
  readonly verifier: ExecutorReceiptVerifier;
}

export function trustedExecutor(publicKeyPem: string, keyId: string = RECEIPT_KEY_ID, extra: readonly { readonly keyId: string; readonly publicKeyPem: string }[] = []) {
  return {
    executorId: EXECUTOR_ID,
    keys: [{ keyId, algorithm: 'ed25519-v1' as const, publicKeyPem }, ...extra.map((key) => ({ keyId: key.keyId, algorithm: 'ed25519-v1' as const, publicKeyPem: key.publicKeyPem }))],
    audiences: [AUDIENCE],
    organizationIds: [ORGANIZATION],
    trustDomains: [TRUST_DOMAIN],
  };
}

export async function receiptDomain(): Promise<ReceiptDomain> {
  const domain = await syntheticDomain();
  const keyDirectory = join(domain.root, 'keys');
  const receiptDirectory = join(domain.root, 'receipts');
  mkdirSync(keyDirectory, { mode: 0o700 });
  mkdirSync(receiptDirectory, { mode: 0o700 });
  const { keyFile, publicKeyPem } = generateReceiptKey(keyDirectory);
  const receiptLedgerPath = join(receiptDirectory, 'receipts.sqlite');
  // The operator's one explicit initialization; the executor never creates a receipt ledger.
  (await openExecutorReceiptLedger(receiptLedgerPath, { executorId: EXECUTOR_ID, audience: AUDIENCE, clock: () => Date.now(), create: true })).close();
  return {
    ...domain,
    keyDirectory,
    keyFile,
    publicKeyPem,
    receiptLedgerPath,
    history: async (capabilityId) => {
      const ledger = await openExecutorReceiptLedger(receiptLedgerPath, { executorId: EXECUTOR_ID, audience: AUDIENCE, clock: () => Date.now() });
      try {
        return ledger.history(capabilityId);
      } finally {
        ledger.close();
      }
    },
    verifier: createExecutorReceiptVerifier({ trustedExecutors: [trustedExecutor(publicKeyPem)] }),
  };
}

/** The synthetic configuration with receipts, over `domain`. */
export function receiptConfiguration(domain: ReceiptDomain, overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return syntheticConfiguration(domain, { executorReceipts: { keyId: RECEIPT_KEY_ID, privateKeyFile: domain.keyFile, receiptLedgerPath: domain.receiptLedgerPath }, ...overrides });
}

export const ISSUER_PINS = [pin(ISSUER_KEY), pin(ISSUER_ROTATED_KEY), pin(OTHER_ISSUER_KEY)].map((key) => ({ keyId: key.keyId, publicKeyPem: key.publicKeyPem }));

export interface ReceiptWorld extends InProcessFlow {
  readonly issuer: ExecutorReceiptIssuer;
  readonly receipts: ExecutorReceiptLedger;
  readonly signer: ExecutorReceiptSigner;
}

/** The C1B flow in process, with a real receipt issuer over its consumption ledger, a real receipt ledger and the executor's key. */
export async function receiptWorld(domain: ReceiptDomain, options: { readonly fault?: (point: ReferenceExecutorFaultPoint) => void; readonly receiptFault?: (point: ReferenceExecutorFaultPoint) => void; readonly clock?: () => number } = {}): Promise<ReceiptWorld> {
  const clock = options.clock ?? (() => Date.now());
  const receipts = await openExecutorReceiptLedger(domain.receiptLedgerPath, { executorId: EXECUTOR_ID, audience: AUDIENCE, clock });
  const signer = loadExecutorReceiptSigner({ executorId: EXECUTOR_ID, keyId: RECEIPT_KEY_ID, privateKeyFile: domain.keyFile, issuerKeys: ISSUER_PINS });
  let built: ExecutorReceiptIssuer | undefined;
  const world = await inProcessFlow(domain, {
    configuration: receiptConfiguration(domain),
    clock,
    ...(options.fault !== undefined ? { fault: options.fault } : {}),
    receiptsFor: (ledger) => {
      built = createExecutorReceiptIssuer({ executorId: EXECUTOR_ID, audience: AUDIENCE, bindingFormat: BINDING_FORMAT, consumption: ledger, receipts, signer, outputDirectory: domain.outputDirectory, ...(options.receiptFault !== undefined ? { fault: options.receiptFault } : {}) });
      return built;
    },
  });
  assert.ok(built !== undefined);
  const issuer = built;
  return {
    ...world,
    issuer,
    receipts,
    signer,
    close: () => {
      world.close();
      receipts.close();
    },
  };
}
